import { readFile, writeFile } from 'node:fs/promises';
import { extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = join(root, 'index.html');
const readText = async file => (await readFile(join(root, file), 'utf8')).replace(/\r\n/g, '\n');

async function imageData(file) {
  const data = await readFile(join(root, file));
  const format = extname(file).slice(1);
  return `data:image/${format};base64,${data.toString('base64')}`;
}

const assets = JSON.parse(await readText('src/mascot-assets.json'));
const app = await build({
  absWorkingDir: root,
  entryPoints: ['src/ui/main.js'],
  bundle: true,
  format: 'iife',
  globalName: 'Jangsoni',
  loader: { '.webp': 'dataurl' },
  write: false,
});

const values = Object.fromEntries(await Promise.all([
  ['BASE_CSS', readText('src/styles/base.css')],
  ['LANDING_CSS', readText('src/styles/landing.css')],
  ['COMPANION_CSS', readText('src/styles/companion.css')],
  ['COMPANION_CHAT_CSS', readText('src/styles/companion-chat.css')],
  ['FSS_DATA', readText('src/data/fss.js')],
  ['KOICD_DATA', readText('src/data/koicd.js')],
  ['ANALYSIS_JS', readText('src/analysis.js')],
  ['HERO_IMAGE', imageData(assets.hero)],
  ['BLINK_IMAGE', imageData(assets.blink)],
  ['COMPANION_BLINK_IMAGE', imageData(assets.companionBlink)],
  ['APP_JS', app.outputFiles[0].text.trimEnd().replace(/<\/script/gi, '<\\/script')],
].map(async ([name, value]) => [name, await value])));

const template = await readText('src/page.html');
const generated = template.replace(/@@([A-Z_]+)@@/g, (token, name) => {
  if (!Object.hasOwn(values, name)) throw new Error(`Unknown template token ${token}`);
  return values[name];
}).replace('<!doctype html>', '<!doctype html>\n<!-- Generated by npm run build from src/. -->');

if (process.argv.includes('--check')) {
  if (await readText('index.html') !== generated) {
    throw new Error('index.html is out of date. Run npm run build.');
  }
} else {
  await writeFile(output, generated, 'utf8');
}
